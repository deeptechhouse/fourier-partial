/** The single App instance. Created on DOM ready. */
let app = null;

function boot() {
  app = new App();
  app.start();
}

if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot, { once: true });
  } else {
    boot();
  }
}

